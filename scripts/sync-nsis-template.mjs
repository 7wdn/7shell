#!/usr/bin/env node
// Writes `src-tauri/nsis/installer.nsi`: the NSIS template Tauri ships, with one line changed.
//
//   node scripts/sync-nsis-template.mjs            rewrite the file
//   node scripts/sync-nsis-template.mjs --check    fail if it is not what this script would write
//
// Why the file exists at all: the text in the bottom left of the installer window is set by Tauri's
// template with a hardcoded `BrandingText "${COPYRIGHT}"` — the copyright notice, which is what a
// 7Shell installer has been showing there. Every other installer shows the product and its version.
// Tauri exposes no setting for that line (`bundle.copyright` is not it: that field is the copyright
// notice on four other platforms too), so the choice is this file or the copyright text.
//
// Why it is generated rather than carried: a copy of a 979-line template is a copy that stops
// matching the day Tauri ships a new one, and nothing would say so. The template is inside the CLI
// the build already uses, so it is read from there — which makes `--check` in the gates a real
// comparison against the version being built with, and makes a Tauri upgrade fail here, by name,
// instead of shipping an installer built from a template nobody has looked at since.

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

import { REPO_ROOT } from "./lib/descriptors.mjs";

const OUTPUT = path.join(REPO_ROOT, "src-tauri", "nsis", "installer.nsi");

/** The line Tauri's template carries, and the one this project wants in the bottom left. */
const FROM = 'BrandingText "${COPYRIGHT}"';
const TO = 'BrandingText "${PRODUCTNAME} ${VERSION}"';

/** Where the CLI keeps its native module: one file per platform, in a package named for it. */
async function findCliModule() {
  const store = path.join(REPO_ROOT, "node_modules", ".pnpm");
  const candidates = (await readdir(store)).filter((name) => name.startsWith("@tauri-apps+cli-"));
  for (const candidate of candidates) {
    const inside = path.join(store, candidate, "node_modules", "@tauri-apps");
    for (const packageName of await readdir(inside)) {
      if (!packageName.startsWith("cli-")) {
        continue;
      }
      const directory = path.join(inside, packageName);
      for (const file of await readdir(directory)) {
        if (file.endsWith(".node")) {
          return path.join(directory, file);
        }
      }
    }
  }
  return null;
}

/** The NUL-terminated string literal the module holds the template in. */
function templateIn(binary, marker) {
  const at = binary.indexOf(Buffer.from(marker, "utf8"));
  if (at === -1) {
    return null;
  }
  let start = at;
  while (start > 0 && binary[start - 1] !== 0) {
    start -= 1;
  }
  let end = at;
  while (end < binary.length && binary[end] !== 0) {
    end += 1;
  }
  return binary.subarray(start, end).toString("utf8");
}

async function cliVersion() {
  const manifest = await readFile(path.join(REPO_ROOT, "node_modules", "@tauri-apps", "cli", "package.json"), "utf8");
  return JSON.parse(manifest).version;
}

async function wanted() {
  const module = await findCliModule();
  if (module === null) {
    throw new Error("the Tauri CLI's native module is not installed: run `pnpm install`");
  }
  const upstream = templateIn(await readFile(module), 'Name "${PRODUCTNAME}"');
  if (upstream === null) {
    throw new Error(`no NSIS template found in ${module}: the CLI may have started shipping it differently`);
  }
  // What came out of the binary has to be the installer template and not one of the other strings
  // around it, because everything after this point would happily rewrite whatever it was given.
  if (!upstream.startsWith("Unicode true") || upstream.split(/\r?\n/).length < 500) {
    throw new Error(
      `what was found in ${module} does not look like the installer template ` +
        `(${upstream.split(/\r?\n/).length} lines, starting "${upstream.slice(0, 40)}")`,
    );
  }

  // The template in the module is CRLF, and the file written here is LF: the repository checks text
  // out with LF on every platform, so anything else would make `--check` fail on a fresh clone.
  const lines = upstream.split(/\r?\n/);
  const at = lines.indexOf(FROM);
  if (at === -1) {
    throw new Error(
      `the template no longer contains \`${FROM}\` — Tauri has changed the line this file exists for, ` +
        "and the branding it sets has to be looked at again",
    );
  }
  lines[at] = TO;

  const header = [
    `; Generated by scripts/sync-nsis-template.mjs from the template inside @tauri-apps/cli ${await cliVersion()}.`,
    "; Do not edit: run the script, which is what the gates check this file against.",
    ";",
    "; One line differs from the template Tauri ships, and it is the line this file exists for. Tauri",
    "; writes the copyright notice into the bottom left of the installer window:",
    ";",
    `;   ${TO}`,
    `;   ${FROM}    <- what Tauri's own template says`,
    ";",
    "; What belongs in that corner is the product and the version, which is what every other",
    "; installer shows there. There is no setting for it, and `bundle.copyright` is not one — that",
    "; field is the copyright notice on four other platforms.",
    "",
  ].join("\n");

  return `${header}${lines.join("\n")}`;
}

const content = await wanted();

if (process.argv.includes("--check")) {
  const current = await readFile(OUTPUT, "utf8").catch(() => null);
  if (current === content) {
    console.log("nsis template: src-tauri/nsis/installer.nsi is what the script would write");
  } else if (current === null) {
    console.error("nsis template: src-tauri/nsis/installer.nsi is missing");
    console.error("  fix: node scripts/sync-nsis-template.mjs");
    process.exitCode = 1;
  } else {
    const before = current.split("\n");
    const after = content.split("\n");
    const firstDifference = after.findIndex((line, index) => line !== before[index]);
    console.error("nsis template: src-tauri/nsis/installer.nsi is not what the script would write");
    console.error(`  line ${firstDifference + 1} of the generated file:`);
    console.error(`    now:  ${before[firstDifference] ?? "(the file ends here)"}`);
    console.error(`    want: ${after[firstDifference] ?? "(the generated file ends here)"}`);
    console.error("  fix: node scripts/sync-nsis-template.mjs");
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, content);
  console.log(`wrote ${path.relative(REPO_ROOT, OUTPUT).split(path.sep).join("/")}`);
}
